def cash_margins_on(day: date) -> dict[str, float]:
    """Cash margin to add per account on ``day`` (rules overlapping one account add up,
    exactly as the ETL's chained CASE terms do)."""
    out: dict[str, float] = {}
    for acc, start, end, amount in DEP_CASH_MARGINS:
        if start <= day <= end:
            out[acc] = out.get(acc, 0.0) + amount
    return out
